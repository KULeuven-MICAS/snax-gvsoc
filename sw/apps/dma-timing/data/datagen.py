"""Writes data.h for dma-timing: the source words the DMA copies from DRAM.

    python3 data/datagen.py > data/data.h

The words are random with NumPy seed 0, so data.h is the same on every run.
"""

import numpy as np

SRC_BYTES = 8192  # the largest case


def main():
    rng = np.random.RandomState(0)
    words = rng.randint(0, 2**32, size=SRC_BYTES // 4, dtype=np.uint64)

    print("// Generated by data/datagen.py (NumPy seed 0). Do not edit.")
    print()
    print("#include <stdint.h>")
    print()
    print(f"#define SRC_BYTES {SRC_BYTES}")
    print()
    print("// In .data, which base.ld places in DRAM (its L3, the program's L2).")
    print("// 64 B is one DMA beat.")
    print("uint32_t src_l2[SRC_BYTES / 4] __attribute__((aligned(64))) = {")
    for i in range(0, len(words), 8):
        row = ", ".join(f"0x{int(w):08x}" for w in words[i:i + 8])
        print(f"    {row},")
    print("};")


if __name__ == "__main__":
    main()
