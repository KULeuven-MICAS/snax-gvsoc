// All the cluster cores are woken up by the bootrom and jump here, and all of
// them run the program, like snRuntime does: a calibration benchmark measures
// the TCDM with every core contending for it, which a single-core runtime
// cannot reproduce.
//
// Only hart 0 goes through the OS initialization (BSS, libc, constructors).
// The others take their stack and wait on the cluster hardware barrier, which
// hart 0 joins at the end of its init (see __pi_init_soc in hal.c), so no
// core enters main before the runtime is up. The barrier is a blocking load
// on the peripheral, so waiting costs no memory traffic and does not perturb
// what the benchmarks measure -- a polled software flag would.

#define CLUSTER_HW_BARRIER (CONFIG_CLUSTER_PERIPH_BASE + 0x40)

    .global _start
    .type   _start, @function
_start:
    // Snitch has no integer multiplier or divider: snitch.sv routes MUL/DIV/
    // REM to the accelerator port (acc_qreq_o.addr = SPATZ), so they are
    // executed by Spatz. Spatz only accepts them once vtype is valid, and out
    // of reset vill is set -- so without this the first `mul` the compiler
    // emits (a printf formatting a number, say) stalls the core forever.
    // snRuntime's crt0 opens the same way (snrt.crt0.init_vec_registers), and
    // it also clears the register file: on RTL the vector regs come out of
    // reset as X and any use propagates.
    //
    // The default march has no 'v' (see pulpos/spatz.py) precisely so the
    // compiler cannot emit vector code, so the assembler is told about the
    // extension just for this block.
    .option push
    .option arch, +v
    li      t0, -1
    vsetvli zero, t0, e32, m8, ta, ma
    vmv.v.i v0, 0
    vmv.v.i v8, 0
    vmv.v.i v16, 0
    vmv.v.i v24, 0
    .option pop

    csrr  t0, mhartid

    // Stack initialization. Hart N takes the Nth slot below `stack`.
    la    x2, stack
    slli  t2, t0, CONFIG_STACK_SIZE_LOG2
    sub   x2, x2, t2

#ifdef CONFIG_SPATZ_MULTICORE
    bnez  t0, __pi_hart_secondary
#else
    bnez  t0, __pi_hart_park
#endif

    // Work-around to cancel call-stack generated by rom on some architectures
    // to not show it in profiler
    la    t0, _start_call_stack_reset_0
    jr    t0
_start_call_stack_reset_0:

    // Do all other initializations from C code
    la    t0, __pi_init_start
    addi  a0, x0, 0
    jalr  x1, t0

#ifdef CONFIG_SPATZ_MULTICORE
    // Secondary harts: rendezvous with hart 0 once the runtime is initialized,
    // then run the program. main() is expected to dispatch on mhartid.
__pi_hart_secondary:
    li    t0, CLUSTER_HW_BARRIER
    lw    t1, 0(t0)
    mv    zero, t1

    la    t0, main
    jalr  x1, t0

    // Nothing to report: hart 0 owns the exit status.
#endif

__pi_hart_park:
    wfi
    j     __pi_hart_park

    .size   _start, . - _start
