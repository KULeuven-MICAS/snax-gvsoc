    .global _start
    .type   _start, @function
_start:

#if defined(CONFIG_MEMCHECK) && defined(__PLATFORM_GVSOC__)
    // Tell the memory checker the application starts here (gv_memcheck_start,
    // semihosting 0x11B). It arms at core reset, which is too early on a chip
    // that boots from a ROM: the firmware initialises every register, and the
    // spills below would then write values it considers initialised onto the
    // application stack. Done here, before the first frame, so nothing has been
    // pushed yet. Inline rather than through gvsoc.h since this is assembly.
    li    a0, 0x11B
    .option norvc
    slli  zero, zero, 0x1f
    ebreak
    srai  zero, zero, 0x7
    .option rvc
#endif

    // Stack initialization. After the call above, so that the stack pointer is
    // established once the checker is armed rather than invalidated by it.
    la    x2, stack

    // Work-around to cancel call-stack generated by rom on some architectures
    // to not show it in profiler
    la    t0, _start_call_stack_reset_0
    jr    t0
_start_call_stack_reset_0:

    // Do all other initializations from C code
    la    t0, __pi_init_start
    addi  a0, x0, 0
    jalr  x1, t0

    .size   _start, . - _start
